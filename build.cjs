/** Build a self-contained Makers function without editing installed packages. */
const fs = require('node:fs')
const path = require('node:path')
const zlib = require('node:zlib')
const { builtinModules } = require('node:module')
const { build } = require('esbuild')

const root = __dirname
const generated = path.join(root, 'src/generated')
const dbPath = path.join(root, 'node_modules/@imaegoo/node-ip2region/data/ip2region.db')
const disabled = new Set([
  '@imaegoo/node-ip2region', 'akismet-api', 'form-data', 'jsdom', 'dompurify',
  'nodemailer', 'mongodb', 'lokijs', 'tencentcloud-sdk-nodejs-tms'
])

async function main () {
  // Only these static files are published; never expose src/tests/the server bundle.
  fs.mkdirSync(path.join(root, 'public'), { recursive: true })
  fs.copyFileSync(path.join(root, 'favicon.ico'), path.join(root, 'public/favicon.ico'))
  // Build inputs are mandatory: fail a deployment rather than silently losing IP lookup.
  const data = fs.readFileSync(dbPath)
  const base64 = zlib.gzipSync(data, { level: 9 }).toString('base64')
  fs.mkdirSync(generated, { recursive: true })
  fs.writeFileSync(path.join(generated, 'ip2region-data.js'),
    `// Generated by build.cjs; do not edit.\nimport { ungzip } from 'pako'\n` +
    `const compressed = ${JSON.stringify(base64)}\nlet buffer\n` +
    `export function getIp2RegionBuffer () {\n  return buffer ??= Buffer.from(ungzip(Buffer.from(compressed, 'base64')))\n}\n`)

  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/entry.js'],
    outfile: 'dist/twikoo.js',
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20.19',
    metafile: true,
    sourcemap: false,
    legalComments: 'eof',
    // Bundled CommonJS packages such as Cap still require supported Node builtins.
    banner: { js: "import { createRequire as __eoCreateRequire } from 'node:module'; const require = __eoCreateRequire(import.meta.url);" },
    plugins: [{
      name: 'makers-platform-dependencies',
      setup (builder) {
        builder.onResolve({ filter: /.*/ }, args => {
          if ([...disabled].some(name => args.path === name || args.path.startsWith(`${name}/`))) {
            return { path: args.path, namespace: 'disabled-library' }
          }
          // Cap always imports fs, even with noFSState + Blob storage hooks. Only
          // this package's unused filesystem backend is replaced; other fs imports
          // are not silently suppressed. An accidental call must fail explicitly.
          if (args.path === 'node:fs/promises' && args.importer.includes('/@cap.js/server/')) {
            return { path: args.path, namespace: 'cap-no-filesystem' }
          }
        })
        builder.onLoad({ filter: /.*/, namespace: 'disabled-library' }, args => ({
          contents: `throw new Error(${JSON.stringify(`Makers 未启用依赖 ${args.path}`)}); export default {};`,
          loader: 'js'
        }))
        builder.onLoad({ filter: /.*/, namespace: 'cap-no-filesystem' }, () => ({
          contents: `const unavailable = async () => { throw new Error('Cap must use noFSState and Blob storage on Makers') }; module.exports = { access: unavailable, mkdir: unavailable, readFile: unavailable, writeFile: unavailable };`,
          loader: 'js'
        }))
      }
    }]
  })
  const builtins = new Set(builtinModules.flatMap(name => [name, `node:${name}`]))
  const external = Object.values(result.metafile.outputs).flatMap(output => output.imports)
    .filter(item => item.external && !builtins.has(item.path))
  if (external.length) throw new Error(`Unbundled dependencies: ${external.map(item => item.path).join(', ')}`)
  fs.writeFileSync(path.join(root, 'dist/metafile.json'), JSON.stringify(result.metafile, null, 2))
  const bytes = fs.statSync(path.join(root, 'dist/twikoo.js')).size
  console.log(`Built Twikoo 2.x Makers function: ${(bytes / 1024 / 1024).toFixed(2)} MiB; Blob schema unchanged.`)
}

main().catch(error => {
  console.error(error)
  process.exitCode = 1
})
